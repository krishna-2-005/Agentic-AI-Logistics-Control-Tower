"""Every number in the manuscripts is a LaTeX macro generated from the newest results freeze.

    python -m src.report.paper_numbers            # writes paper/numbers.tex
    python -m src.report.paper_numbers --check    # exit 1 if paper/numbers.tex is stale or a manuscript
                                                  # uses a number macro that is not defined

The text of a paper may not contain a result typed by hand. It writes `\\fzBottlenecks`, and this module
defines that macro from the value `results_freeze_v*.json` holds for the id `bottlenecks`. The freeze in turn
records which file each value came from and what that file hashed to (`src.ml.results_freeze`), so a number in
the PDF can be followed to a file in `benchmarks/raw/` and cannot drift from it without `--verify` noticing.

Macro names: `\\fz` + the freeze id in CamelCase, with digits spelled out because TeX control words cannot
contain them (`mae_v2` becomes `\\fzMaeVTwo`). Integers are printed with thousands separators (international
grouping); floats as stored; booleans as `true`/`false`.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

from src.common import config

PAPER_DIR = config.REPO_ROOT / "paper"
OUT = PAPER_DIR / "numbers.tex"
PREFIX = "fz"
DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]
USED = re.compile(r"\\(" + PREFIX + r"[A-Za-z]+)")


def newest_freeze() -> Path:
    """The highest-numbered `results_freeze_v<N>.json`; a lower one is never used silently."""
    found = [(int(m.group(1)), p) for p in config.BENCHMARKS_DIR.glob("results_freeze_v*.json")
             if (m := re.fullmatch(r"results_freeze_v(\d+)\.json", p.name))]
    if not found:
        raise FileNotFoundError("no benchmarks/results_freeze_v*.json")
    return max(found)[1]


def macro_name(freeze_id: str) -> str:
    camel = "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", freeze_id) if part)
    spelled = "".join(DIGITS[int(c)] if c.isdigit() else c for c in camel)
    return PREFIX + spelled


def tex_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return f"{value:,}".replace(",", "{,}")
    if isinstance(value, float):
        text = repr(value)
        whole, _, frac = text.partition(".")
        grouped = f"{int(whole):,}".replace(",", "{,}") if whole.lstrip("-").isdigit() else whole
        return grouped + ("." + frac if frac and frac != "0" else "")
    return str(value).replace("\\", "").replace("_", r"\_").replace("%", r"\%").replace("&", r"\&").replace("#", r"\#")


def render(freeze_path: Path | None = None) -> str:
    path = freeze_path or newest_freeze()
    freeze = json.loads(path.read_text(encoding="utf-8"))
    lines = [
        "% GENERATED by `python -m src.report.paper_numbers`. Do not edit: change the freeze and regenerate.",
        f"% source: benchmarks/{path.name}  sha256 {hashlib.sha256(path.read_bytes()).hexdigest()[:16]}  "
        f"frozen_at {freeze['frozen_at']}  values {freeze['n_values']}",
    ]
    seen: dict[str, str] = {}
    for item in freeze["values"]:
        name = macro_name(item["id"])
        if name in seen:
            raise ValueError(f"freeze ids {seen[name]!r} and {item['id']!r} both become \\{name}")
        seen[name] = item["id"]
        lines.append(f"\\providecommand{{\\{name}}}{{{tex_value(item['value'])}}} % {item['id']} ({item['unit'] or 'text'})")
    return "\n".join(lines) + "\n"


def used_macros(root: Path = PAPER_DIR) -> dict[str, list[str]]:
    """Every `\\fz...` control word the manuscripts use, with the files that use it."""
    out: dict[str, list[str]] = {}
    for tex in sorted(root.rglob("*.tex")):
        if tex.name == OUT.name:
            continue
        for name in set(USED.findall(tex.read_text(encoding="utf-8"))):
            out.setdefault(name, []).append(str(tex.relative_to(root)))
    return out


def check() -> list[str]:
    problems = []
    expected = render()
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != expected:
        problems.append(f"{OUT.name} is missing or differs from what the newest freeze generates")
    defined = {macro_name(i["id"]) for i in json.loads(newest_freeze().read_text(encoding="utf-8"))["values"]}
    for name, files in used_macros().items():
        if name not in defined:
            problems.append(f"\\{name} is used in {files} but the freeze defines no such value")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        problems = check()
        for problem in problems:
            print(problem)
        return 1 if problems else 0
    PAPER_DIR.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT} from {newest_freeze().name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
